// Build a standalone, explicitly labelled portfolio. Never reads .env or cloud data.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'output', 'github-pages');
const pages = ['index.html', 'connexion.html', 'compte.html', 'titre.html', 'netflix.html', 'prime-video.html', 'paramount.html', 'disney.html', 'marvel.html', 'credits.html'];
const replacements = { 'firebase-auth.js': 'demo/auth.js', 'personal-sync.js': 'demo/personal.js', 'title-video.js': 'demo/video.js' };
const localRequests = new Set(['profiles.js', 'tmdb-client.js', 'hero.js', 'profile-dashboard.js']);
function readData(file) { const source = fs.readFileSync(path.join(root, file), 'utf8'); return JSON.parse(source.slice(source.indexOf('{'), source.lastIndexOf('}') + 1)); }
function write(file, text) { const target = path.join(output, file); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, text); }
function relativeLinks(text) {
  return text.replace(/(["'`])\/(assets\/|titre\.html|connexion\.html|compte\.html|index\.html)/g, '$1$2');
}
function buildDemo() {
  // Only this fixed, generated directory may be replaced. Never remove an unknown directory.
  if (fs.existsSync(output)) {
    if (path.relative(root, output) !== path.join('output', 'github-pages') || !fs.existsSync(path.join(output, '.hessflix-demo-build'))) throw Error('Refusing to replace an unrecognised output directory');
    fs.rmSync(output, { recursive: true });
  }
  write('.hessflix-demo-build', 'Generated by scripts/build-demo.cjs\n');
  const discovery = readData('discovery-data.js'), platforms = readData('platform-catalogue-data.js'), guides = readData('episode-data.js');
  const anime = new Set(['jw-tm44887', 'jw-ts250831', 'jw-ts20682', 'jw-ts529703']);
  const items = [...new Map([...discovery.items, ...platforms.items].map(item => [item.id, item])).values()].map(item => ({
    ...item, isAnime: anime.has(item.id),
    platforms: Object.entries(platforms.providers).filter(([, provider]) => provider.itemIds.includes(item.id)).map(([id]) => id)
  }));
  // Keep real reference metadata and credits, but no video links or admin records.
  for (const item of items) {
    if (!/^assets\/discovery\/[a-z0-9-]+\.(jpg|png|webp)$/.test(item.image || '')) throw Error('Demo poster must be local');
    if ('video' in item || 'embedURL' in item) throw Error('Playback sources must not enter the demo');
  }
  const data = { items, collections: discovery.collections, providers: platforms.providers, updatedAt: discovery.updatedAt, checkedAt: platforms.checkedAt, guides };
  write('demo-data.js', 'window.HessflixDemoCatalogue=' + JSON.stringify(data).replace(/</g, '\\u003c') + ';\n');
  write('catalogue-data.js', "window.HessflixCatalogueApproved=true;window.HessflixCatalogueStatus='ready';window.HessflixCatalogueNext=null;window.MovixDiscovery={...window.HessflixDemoCatalogue};window.MovixPlatformCatalogue={...window.HessflixDemoCatalogue,country:'FR'};window.HessflixEpisodes=window.HessflixDemoCatalogue.guides;\n");
  const resources = new Set();
  const csp = "default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; media-src 'self'; font-src 'self'; connect-src 'none'; frame-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'";
  for (const file of pages) {
    let html = fs.readFileSync(path.join(root, file), 'utf8');
    if (file === 'connexion.html') {
      html = html.replace(/<section class="auth-card"[\s\S]*?<\/section>/, '<section class="auth-card demo-login-card" aria-labelledby="demo-login-title"><h2 id="demo-login-title">Votre place est réservée.</h2><div class="demo-login-copy"><p>Explorez Hessflix avec deux profils fictifs : Cinéphile et Explorateur.</p><ul><li>Recherchez des films, séries et animes.</li><li>Essayez les favoris et le suivi des épisodes.</li><li>Personnalisez vos profils sans adresse e-mail ni mot de passe.</li></ul><p>Vos essais restent dans ce navigateur. Aucun compte réel n’est créé, aucune vidéo n’est diffusée.</p></div><button type="button" class="auth-submit" id="demo-enter">Entrer dans la démo</button></section>');
      html = html.replace('Connexion — Hessflix', 'Essayer la démo — Hessflix');
    }
    // No login form, Firebase SDK or admin surface is copied into the demo.
    html = html.replace(/<script src="(?:account-login|auth-session|video-player)\.js" defer><\/script>/g, '');
    html = relativeLinks(html);
    html = html.replace(/<head>/, '<head>\n<meta http-equiv="Content-Security-Policy" content="' + csp + '">\n<meta name="referrer" content="no-referrer">\n<link rel="stylesheet" href="demo.css">\n<script src="demo-data.js"></script>\n<script src="demo-runtime.js"></script>');
    html = html.replace(/Le lecteur externe Vidmoly[\s\S]*?<\/p>/, 'Démonstration du parcours de lecture : aucun lecteur tiers ni aucune vidéo ne sont chargés.</p>');
    for (const match of html.matchAll(/(?:src|href)="([^"?#]+\.(?:js|css))"/g)) {
      if (!match[1].startsWith('http')) resources.add(match[1]);
    }
    write(file, html);
  }
  for (const file of resources) {
    if (['demo-data.js', 'catalogue-data.js', 'demo.css', 'demo-runtime.js'].includes(file)) continue;
    if (!/^[a-z0-9-]+\.(js|css)$/.test(file) || file.startsWith('admin')) throw Error('Unexpected public dependency: ' + file);
    let text = fs.readFileSync(path.join(root, replacements[file] || file), 'utf8');
    if (localRequests.has(file)) text = text.replace(/\bfetch\(/g, 'window.HessflixDemo.request(');
    text = relativeLinks(text);
    if (file.endsWith('.css')) text = text.replace(/@import url\('https:\/\/fonts\.googleapis\.com\/[^']+'\);/g, '');
    if (file === 'account.js') text = text.replace("return account.provider === 'google.com' ? 'Connecté avec Google' : 'Connecté avec votre compte';", "return 'Profil fictif · Démonstration locale';").replace('Profil <span class="account-status">(Déconnecté)</span>', 'Essayer la démo');
    if (file === 'profile-dashboard.js') text = text.replace('Relancer la synchronisation', 'Actualiser mes listes locales').replace('Les listes sont synchronisées avec votre compte, séparément pour chaque profil. Les modifications hors ligne restent en attente sur cet appareil.', 'Démonstration : les listes et les épisodes sont propres à chaque profil et restent uniquement dans ce navigateur. Aucun compte réel ni synchronisation entre appareils.');
    if (file === 'title-page.js') text = text.replace("'Informations TMDB · '", "'Métadonnées d’exemple enregistrées · '");
    if (file === 'platform-page.js') text = text.replace('titres publiés · Sélection Hessflix · France', 'titres d’exemple · Disponibilités historiques, à vérifier');
    write(file, text);
  }
  write('demo-runtime.js', fs.readFileSync(path.join(root, 'demo/runtime.js')));
  write('demo.css', fs.readFileSync(path.join(root, 'demo/demo.css')));
  // Only versioned public media; no working screenshots, database or credentials.
  const assets = execFileSync('git', ['ls-files', '-z', '--', 'assets'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
  for (const asset of assets) {
    if (!/\.(png|jpe?g|webp|svg|mp4|woff2?)$/i.test(asset) && !/\/(SOURCES|PLATFORMS)\.md$/.test(asset)) continue;
    const target = path.join(output, asset); fs.mkdirSync(path.dirname(target), { recursive: true }); fs.copyFileSync(path.join(root, asset), target);
  }
  for (const file of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) write(file, fs.readFileSync(path.join(root, file)));
  write('.nojekyll', '');
  console.log(`Static demo: ${items.length} example titles, ${pages.length} pages. No cloud access.`);
  return output;
}
if (require.main === module) buildDemo();
module.exports = { buildDemo, output, pages };
